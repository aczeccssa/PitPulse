use std::{env, fmt::Write as _, fs, path::Path};

fn main() {
    // The dashboard shell is embedded with `include_str!` from resources/web.
    // Watch the directory so changing an asset always rebuilds the binary that
    // serves it, instead of leaving a stale page on disk.
    println!("cargo:rerun-if-changed=resources/web");
    println!("cargo:rerun-if-changed=resources/motorsport");

    // Season artwork: resources/motorsport/<season>/<kind>/<id>.png. Keys keep
    // their relative path so one route can serve the whole tree.
    emit_asset_table(
        "resources/motorsport",
        "MOTORSPORT_ASSETS",
        "motorsport_assets.rs",
        true,
    );
    // Flags and other season-less artwork still live beside the shell.
    emit_asset_table(
        "resources/web/motorsport",
        "MOTORSPORT_LEGACY_ASSETS",
        "motorsport_legacy_assets.rs",
        false,
    );
    emit_asset_index("resources/motorsport", "motorsport_index.rs");
    println!("cargo:rerun-if-changed=resources/media");
    emit_asset_table("resources/media", "NATIVE_ASSETS", "native_assets.rs", true);
}

fn png_paths(root: &Path, relative: &Path, recursive: bool, out: &mut Vec<(String, String)>) {
    let Ok(read_dir) = fs::read_dir(root.join(relative)) else {
        return;
    };
    for entry in read_dir.flatten() {
        let name = entry.file_name().to_string_lossy().into_owned();
        let child = relative.join(&name);
        let is_dir = entry.file_type().map(|kind| kind.is_dir()).unwrap_or(false);
        if is_dir {
            if recursive {
                png_paths(root, &child, recursive, out);
            }
            continue;
        }
        if !name.ends_with(".png") {
            continue;
        }
        let key = child.to_string_lossy().replace('\\', "/");
        let path = root.join(&child).to_string_lossy().into_owned();
        out.push((key, path.replace('\\', "\\\\")));
    }
}

/// Build a `&[(&str, &[u8])]` table for a directory of images so the router can
/// serve any of them without one handler per file. `include_bytes!` paths are
/// absolute, because the generated file lives in `OUT_DIR`.
fn emit_asset_table(dir: &str, symbol: &str, file_name: &str, recursive: bool) {
    let manifest_dir = env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR");
    let root = Path::new(&manifest_dir).join(dir);
    let mut entries: Vec<(String, String)> = Vec::new();
    png_paths(&root, Path::new(""), recursive, &mut entries);
    entries.sort();

    let mut code = String::new();
    let _ = writeln!(code, "/// Generated by build.rs from {dir}.");
    let _ = writeln!(code, "pub static {symbol}: &[(&str, &[u8])] = &[");
    for (name, path) in entries {
        let _ = writeln!(code, "    ({name:?}, include_bytes!({path:?})),");
    }
    let _ = writeln!(code, "];");

    let out = Path::new(&env::var("OUT_DIR").expect("OUT_DIR")).join(file_name);
    fs::write(out, code).expect("write generated asset table");
}

/// Emit the browser-side index of available artwork so the page can resolve
/// `{season}/{kind}/{id}` without probing for files that do not exist.
fn emit_asset_index(dir: &str, file_name: &str) {
    let manifest_dir = env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR");
    let root = Path::new(&manifest_dir).join(dir);
    let mut entries: Vec<(String, String)> = Vec::new();
    png_paths(&root, Path::new(""), true, &mut entries);
    entries.sort();

    let mut keys = String::new();
    for (key, _) in &entries {
        let stem = key.strip_suffix(".png").unwrap_or(key);
        let _ = write!(keys, "\\\"{stem}\\\":1,");
    }

    let mut code = String::new();
    let _ = writeln!(code, "/// Generated by build.rs from {dir}.");
    let _ = writeln!(
        code,
        "pub static MOTORSPORT_INDEX_JS: &str = \"window.PITPULSE_ASSETS={{{keys}}};\\n\";"
    );

    let out = Path::new(&env::var("OUT_DIR").expect("OUT_DIR")).join(file_name);
    fs::write(out, code).expect("write generated asset index");
}
